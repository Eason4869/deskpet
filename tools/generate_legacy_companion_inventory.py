"""Generate small trusted inventories for retaining released X/G default caches.

No artwork is embedded here. Run --check in CI after changing the canonical
bundled source manifests or PNGs; deliberate supported snapshots are reviewed.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]


def binary_string(value):
    data = value.encode('utf-8')
    size = len(data)
    prefix = bytearray()
    while size >= 128:
        prefix.append((size & 127) | 128)
        size >>= 7
    prefix.append(size)
    return prefix + data


def generate():
    entries = []
    for role in ('xiaobei', 'gugugaga'):
        root = ROOT / 'assets/bundled-skins' / role
        manifest = json.loads((root / 'pet.json').read_text(encoding='utf-8-sig'))
        references = {'pet.json', manifest['preview'], manifest['gaze']['file']}
        if manifest.get('avatar'):
            references.add(manifest['avatar'])
        for group in ('animations', 'extra_animations', 'alternate_animations'):
            references.update(clip['file'] for clip in manifest.get(group, {}).values())
        files, version_bytes = [], bytearray()
        for name in sorted(references):
            data = (root / name).read_bytes()
            digest = hashlib.sha256(data).digest()
            version_bytes += binary_string(name) + struct.pack('<q', len(data)) + digest
            files.append({'path': name, 'size': len(data), 'sha256': digest.hex()})
        entries.append({'id': role, 'cache_version': hashlib.sha256(version_bytes).hexdigest(), 'manifest': manifest, 'files': files})
    data = json.dumps({'schema_version': 1, 'roles': entries}, ensure_ascii=False, separators=(',', ':'))
    literal = '@"' + data.replace('"', '""') + '"'
    return '// Generated by tools/generate_legacy_companion_inventory.py; metadata and SHA256 only.\nnamespace Dafeiyu\n{\n    internal static class OfficialCompanionLegacyData\n    {\n        internal const string Json = ' + literal + ';\n    }\n}\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'src/OfficialCompanionLegacyData.cs'
    result = generate()
    if args.check:
        if not target.is_file() or target.read_text(encoding='utf-8') != result:
            raise SystemExit('Legacy companion inventory is stale; regenerate and review supported source snapshot changes.')
        print('PASS canonical legacy inventory matches repository manifests and complete file hashes')
    else:
        target.write_text(result, encoding='utf-8', newline='')
        print('Generated small trusted legacy inventory: ' + str(len(result.encode('utf-8'))) + ' bytes')


if __name__ == '__main__':
    main()
